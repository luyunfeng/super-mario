export function buildBriefingPrompt(kind: string, factsText: string, timezone: string): string {
  const label = ({ morning: '早间', evening: '晚间', interval: '间隔', project: '项目' } as Record<string, string>)[kind] ?? '';
  const guidance = kind === 'morning'
    ? [
        '这是早间简报。请先用手机端一眼能看懂的结构整理：',
        '1. **今天最该先处理的 1–3 件事**（优先待你决定、逾期/今日到期、阻塞中的任务或待回复消息）。',
        '2. **今日日程与会前准备**：如果已注册 calendar_agenda 工具，请先查今天日程，标出时间冲突与入会链接；对重要会议，可在必要时说明会前需核对的要点。',
        '3. **各项目进展与待验收**：简明分点，区分“执行结束待验收”和“已完成待办”。',
      ].join('\n')
    : kind === 'evening'
      ? [
          '这是晚间回顾。请整理：',
          '1. **今日完成与产出**（已完成待办、已结束待验收的执行）。',
          '2. **仍在运行、失败或卡住的事项**（写清失败原因或卡点）。',
          '3. **明早需要接续或待你决定的事项**。',
        ].join('\n')
      : '这是阶段简报。只突出本时间窗内的新增变化、失败原因和待你决定事项；若无实质变化，一句话说明即可。';

  return [
    `请基于以下由程序统计的唯一真实事实生成一份简洁、高密度的工作台${label}简报（时区：${timezone}）。`,
    guidance,
    '约束：',
    '- 严格以事实为准，不编造未出现的数字、进展或完成状态；执行结束不等于待办验收完成。',
    '- 面向飞书手机端阅读：先给结论，短段落与分点列表，不使用宽表格，控制在 900 字以内。',
    '- 若有未接入的数据源（例如日历未配置）或信息缺口，直接跳过或一句说明，不编造。',
    '',
    '程序统计事实：',
    factsText,
  ].join('\n');
}
