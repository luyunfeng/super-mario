import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { chromium, expect } from '@playwright/test';
import { startServer } from '../apps/server/src/index.ts';

test('订阅分拣规则允许 4000 个码点，支持改回退级别、清空和重载', {timeout:35000},async t=>{
  const dir=await mkdtemp(join(tmpdir(),'sm-sub-triage-web-'));
  const server=await startServer({dataDir:dir,port:0,host:'127.0.0.1',token:'offline-triage',demo:true});
  t.after(async()=>{await server.close();await rm(dir,{recursive:true,force:true});});
  const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE});
  t.after(()=>browser.close());
  const page=await browser.newPage();page.setDefaultTimeout(6500);
  await page.addInitScript(()=>localStorage.setItem('sm.splash.seen','true'));
  await page.goto(server.url+'/#memory?token=offline-triage');
  const launch=page.getByRole('button',{name:'来源订阅',exact:true});
  await launch.click();
  const subs=page.getByRole('dialog',{name:'来源订阅',exact:true});
  await subs.getByLabel('来源连接器').selectOption('release-source.releases');
  await subs.getByLabel('仓库（owner/repo）').fill('test/fixture');
  await subs.getByLabel('订阅名称').fill('合成分拣订阅');
  const original='🧪'.repeat(4000);
  await subs.getByText('收件箱分拣',{exact:true}).click();
  const rules=subs.getByLabel('分拣规则');
  await rules.fill(original+'甲');
  await subs.getByRole('button',{name:'创建订阅'}).click();
  await expect(rules).toHaveJSProperty('validationMessage','分拣规则最多 4000 字。');
  assert.equal(server.app.subscriptions.service().list().length,0);
  await rules.fill(original);
  await subs.getByLabel('回退级别').selectOption('wait');
  await subs.getByRole('button',{name:'创建订阅'}).click();
  const row=subs.getByRole('article',{name:'合成分拣订阅'});
  const editor=page.getByRole('dialog',{name:'编辑订阅'});
  const edit=row.getByRole('button',{name:'编辑订阅'});
  await edit.click();
  await expect(editor.getByLabel('分拣规则')).toHaveValue(original);
  await expect(editor.getByLabel('回退级别')).toHaveValue('wait');
  await editor.getByLabel('分拣规则').fill('有关修复的版本需要处理。\n其他版本作为知会。');
  await editor.getByLabel('回退级别').selectOption('action');
  await editor.getByRole('button',{name:'保存订阅'}).click();
  await expect(editor).toHaveCount(0);
  await page.reload();await launch.click();await edit.click();
  await expect(editor.getByLabel('分拣规则')).toHaveValue('有关修复的版本需要处理。\n其他版本作为知会。');
  await expect(editor.getByLabel('回退级别')).toHaveValue('action');
  await editor.getByLabel('分拣规则').fill('');
  await editor.getByLabel('回退级别').selectOption('auto');
  await editor.getByRole('button',{name:'保存订阅'}).click();
  await expect(editor).toHaveCount(0);
  await page.reload();await launch.click();await edit.click();
  await editor.getByText('收件箱分拣',{exact:true}).click();
  await expect(editor.getByLabel('分拣规则')).toHaveValue('');
  await expect(editor.getByLabel('回退级别')).toHaveValue('auto');
});
