import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import test from 'node:test';
import {chromium,expect} from '@playwright/test';
import {startServer} from '../apps/server/src/index.ts';

test('独立 Web 对话实际收发、刷新及草稿隔离，停用或失效链接保留在原范围',{timeout:40000},async t=>{
  const dir=await mkdtemp(join(tmpdir(),'independent-web-chats-')),token='synthetic-thread-browser';
  const server=await startServer({dataDir:dir,port:0,host:'127.0.0.1',demo:true,token});
  const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE});
  t.after(async()=>{await browser.close();await server.close();await rm(dir,{recursive:true,force:true});});
  const page=await browser.newPage(),errors:string[]=[],mainPosts:string[]=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',r=>{if(r.method()==='POST' && new URL(r.url()).pathname==='/api/v1/messages')mainPosts.push(r.method());});
  await page.addInitScript(()=>localStorage.setItem('sm.splash.seen','true'));
  await page.goto(server.url+'/#chat?token='+token);
  const main=page.locator('#message-text'),thread=page.getByRole('textbox',{name:'给独立对话发消息'});
  await main.fill('主对话的未发草稿');
  const create=async(title:string)=>{
    await page.getByRole('button',{name:'独立对话',exact:true}).click();
    const drawer=page.getByRole('dialog',{name:'独立对话'});
    await drawer.getByLabel('对话标题').fill(title);
    await drawer.getByRole('button',{name:'创建对话'}).click();
    await expect(page.getByRole('heading',{name:title,exact:true})).toBeVisible();
    return page.url();
  };
  const first=await create('验收记录甲'),text='仅在第一条线的合成消息';
  await expect(main).toBeHidden();await expect(thread).toHaveValue('');
  await thread.fill(text);await thread.press('Enter');
  const messages=page.locator('[aria-label="独立对话内容"] .msgs');
  await expect(messages.locator('.msg--user')).toHaveText(text);
  await expect(messages.locator('.msg--assistant').first()).toBeVisible();
  await expect(thread).toHaveValue('');
  await thread.fill('第一条线的未发草稿');await page.reload();
  await expect(thread).toHaveValue('第一条线的未发草稿');
  await expect(messages.locator('.msg--user')).toHaveText(text);
  await create('验收记录乙');
  await expect(messages.locator('article')).toHaveCount(0);await expect(thread).toHaveValue('');
  await page.getByRole('button',{name:'独立对话',exact:true}).click();
  await page.getByRole('dialog',{name:'独立对话'}).getByRole('link',{name:'验收记录甲'}).click();
  await expect(page).toHaveURL(first);await expect(thread).toHaveValue('第一条线的未发草稿');
  await page.getByRole('link',{name:'返回主对话'}).click();await expect(main).toHaveValue('主对话的未发草稿');
  await page.goto(server.url+'/#chat?thread=not-valid');
  await expect(page.getByText('独立对话链接无效。')).toBeVisible();await expect(main).toBeHidden();await expect(thread).toBeHidden();
  await page.goto(first);await expect(thread).toBeVisible();
  const disabled=await fetch(server.url+'/api/v1/plugins/web-conversations',{method:'POST',headers:{authorization:'Bearer '+token,'content-type':'application/json'},body:JSON.stringify({enabled:false})});
  assert.equal(disabled.status,200);
  await expect(page.getByText('独立对话插件不可用。')).toBeVisible();await expect(thread).toBeHidden();await expect(main).toBeHidden();
  await expect(messages.locator('article')).toHaveCount(0);
  await page.getByRole('link',{name:'返回主对话'}).click();await expect(main).toHaveValue('主对话的未发草稿');
  await expect(page.getByRole('button',{name:'独立对话',exact:true})).toHaveCount(0);
  assert.deepEqual(mainPosts,[]);assert.deepEqual(errors,[]);
});
