import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import test from 'node:test';
import {chromium,expect} from '@playwright/test';
import {startServer} from '../apps/server/src/index.ts';

test('管理员可为尚未连接的执行机签发、清除展示及确认撤销专用凭据',async t=>{
  const dataDir=await mkdtemp(join(tmpdir(),'admin-machine-cred-')),token='synthetic-admin-machine-credentials';
  const server=await startServer({dataDir,port:0,host:'127.0.0.1',token,demo:true});
  t.after(async()=>{await server.close();await rm(dataDir,{recursive:true,force:true});});
  const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE});
  t.after(()=>browser.close());
  const context=await browser.newContext(),base=server.url+'/api/v1/admin/';
  const code=await context.request.post(base+'setup-code',{headers:{authorization:'Bearer '+token},data:{}});
  assert.equal(code.status(),200);
  const setup=await context.request.post(base+'setup',{data:{code:(await code.json()).code,password:'synthetic-admin-password'}});
  assert.equal(setup.status(),200);
  const page=await context.newPage();
  await page.goto(server.url+'/admin.html');
  const panel=page.getByRole('region',{name:'专用执行机凭据'});
  await panel.getByRole('button',{name:'查看专用凭据'}).click();
  await expect(panel).toContainText('还没有专用执行机凭据');
  const id='synthetic-offline-node';
  await panel.getByRole('textbox',{name:'签发凭据的执行机 ID'}).fill(id);
  await panel.getByRole('button',{name:'签发专用凭据'}).click();
  const issued=panel.getByRole('textbox',{name:'新签发的执行机凭据'});
  await expect(issued).toBeVisible();
  const secret=await issued.inputValue();
  assert.ok(secret.length>20);
  assert.equal(await page.evaluate(value=>[location.href,...Object.values(localStorage),...Object.values(sessionStorage)].some(s=>String(s).includes(value)),secret),false);
  await panel.getByRole('button',{name:'清除已显示凭据'}).click();
  await expect(issued).toHaveCount(0);
  await page.reload();
  await panel.getByRole('button',{name:'查看专用凭据'}).click();
  await expect(issued).toHaveCount(0);
  const revoke=panel.getByRole('button',{name:'撤销 '+id,exact:true});
  await revoke.click();await panel.getByRole('button',{name:'取消撤销'}).click();
  await expect(revoke).toBeVisible();await revoke.click();
  await panel.getByRole('button',{name:'确认撤销'}).click();
  await expect(panel).toContainText('还没有专用执行机凭据');
});
