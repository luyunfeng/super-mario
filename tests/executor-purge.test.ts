import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdtemp, mkdir, readFile, readdir, rename, rm, symlink, unlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createExecutionServices } from '../plugins/executors.ts';
import type { TerminalHost } from '../packages/plugin-sdk/src/index.ts';

test('节点只清理指定会话，拒绝非结束态和软链，丢回执后可跨重启重试', async t => {
  const root = await mkdtemp(join(tmpdir(), 'mario-executor-purge-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const dataDir = join(root, 'node'), cwd = join(root, 'workspace');
  const tasks = join(dataDir, 'task-results');
  await mkdir(tasks, { recursive: true });
  await mkdir(cwd);
  const userFile = join(cwd, 'command-output');
  await writeFile(userFile, 'user output');
  const machineId = 'fixture';
  const binding = () => ({ sessionId: randomUUID(), paneId: randomUUID(), machineId, executorId: 'codex', cwd, createdAt: new Date().toISOString() });
  const first = binding(), other = binding();
  await writeFile(join(dataDir, 'executor-sessions.json'), JSON.stringify([first, other]));
  const result = join(tasks, first.sessionId + '.json');
  const config = join(tasks, first.sessionId + '.config.json');
  await writeFile(config, '{}');
  await writeFile(result, JSON.stringify({ state: 'failed', text: 'not final' }));
  const otherConfig = other.sessionId + '.config.json';
  await writeFile(join(tasks, otherConfig), 'unrelated');
  // This RPC may touch managed files only. Even inspecting the external host fails the test.
  const host = new Proxy({} as TerminalHost, { get() { throw new Error('unexpected terminal access'); } });
  const service = () => createExecutionServices({ dataDir, machineId, host });
  let node = service();
  const fields = { projectId: randomUUID(), runId: randomUUID(), sessionId: first.sessionId, status: 'failed' };
  const purge = (patch = {}) => node.handlers['workspace.executor.purge']!({ ...fields, ...patch }, () => {});
  await assert.rejects(purge({ status: 'running' }), /已结束/);
  await assert.rejects(purge({ sessionId: '../workspace' }), /已结束/);
  await assert.rejects(purge({ sessionId: randomUUID() }));
  await assert.rejects(purge(), /结束证据/);
  await writeFile(result, JSON.stringify({ state: 'failed', exitCode: 1 }));
  const last = result + '.last-message';
  await symlink(userFile, last);
  await assert.rejects(purge(), /路径类型异常/);
  assert.equal(await readFile(config, 'utf8'), '{}');
  await unlink(last);
  await writeFile(last, 'managed last message');
  await rename(tasks, tasks + '-original');
  await symlink(tasks + '-original', tasks);
  await assert.rejects(purge());
  await unlink(tasks);
  await rename(tasks + '-original', tasks);
  const receipt = { projectId: fields.projectId, runId: fields.runId, sessionId: fields.sessionId, purged: true };
  assert.deepEqual(await purge(), receipt);
  await node.close();
  node = service();
  assert.deepEqual(await purge(), receipt);
  await assert.rejects(purge({ runId: randomUUID() }), /不匹配/);
  assert.deepEqual(await node.handlers['executor.sessions']!({}, () => {}), [other]);
  await assert.rejects(node.handlers['executor.result']!({ sessionId: first.sessionId }, () => {}), /not bound/);
  assert.deepEqual(await readdir(tasks), [otherConfig]);
  assert.equal(await readFile(userFile, 'utf8'), 'user output');
  await node.close();
});
