import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { chromium, expect } from '@playwright/test';
import { startServer } from '../apps/server/src/index.ts';

test('Web 会话状态只展示当前入口及项目内的最近发言，手动刷新可见新记录', async t => {
  const dataDir = await mkdtemp(join(tmpdir(), 'mario-conversation-status-'));
  const token = 'conversation-status-fixture';
  const server = await startServer({ host: '127.0.0.1', port: 0, dataDir, token, demo: true });
  let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
  t.after(async () => { await browser?.close(); await server.close(); await rm(dataDir, { recursive: true, force: true }); });
  const p = server.app.projects.create({ name: '合成项目甲' });
  const add = (id: string, conversationId: string, text: string, time: number, projectId?: string) => {
    server.app.store.put('messages', id, { id, conversationId, role: 'assistant', text, projectId, status: 'done', createdAt: new Date(time).toISOString() });
  };
  const now = Date.now();
  add('main-p', 'main', '主对话中甲的记录', now, p.id);
  add('main-other', 'main', '其他范围的记录', now + 1);
  const target = 'project:' + p.id + ':work';
  add('work-p', target, '工作会话甲的记录', now, p.id);
  browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE });
  const page = await browser.newPage();
  await page.addInitScript(() => localStorage.setItem('sm.splash.seen', 'true'));
  await page.goto(server.url + '/#chat?token=' + token);
  await page.locator('#scope-select').selectOption(p.id);
  const open = page.getByRole('button', { name: '会话状态', exact: true });
  const drawer = page.getByRole('dialog', { name: '会话状态' });
  await open.click();
  await expect(drawer).toContainText('主对话中甲的记录');
  await expect(drawer).not.toContainText('其他范围的记录');
  await drawer.getByRole('button', { name: '关闭' }).click();
  await page.goto(server.url + '/#projects/' + p.id + '/workspace');
  await open.click();
  await expect(drawer).toContainText('工作会话甲的记录');
  await expect(drawer).not.toContainText('主对话中甲的记录');
  add('work-latest', target, '刷新后甲的回复', now + 2, p.id);
  await drawer.getByRole('button', { name: '刷新状态' }).click();
  await expect(drawer).toContainText('刷新后甲的回复');
  await drawer.getByRole('link', { name: '查看原文' }).click();
  await expect(page).toHaveURL(new RegExp('at=work-latest$'));
  await expect(page.locator('[data-id="work-latest"]').first()).toContainText('刷新后甲的回复');
  await open.click();
  const endpoint = server.url + '/api/v1/conversation-status';
  assert.equal((await fetch(endpoint, { method: 'POST', body: '{}' })).status, 401);
  const headers = { authorization: 'Bearer ' + token };
  assert.equal((await fetch(endpoint, { method: 'POST', headers, body: JSON.stringify({ target: 'main', conversationId: target }) })).status, 400);
  assert.ok((await page.request.post(server.url + '/api/v1/plugins/conversation-search', { headers, data: { enabled: false } })).ok());
  await expect(drawer).toBeHidden();
  await expect(open).toBeHidden();
});
