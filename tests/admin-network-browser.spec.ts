import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import test from 'node:test';
import QRCode from 'qrcode';
import {chromium,expect} from '@playwright/test';
import {startServer} from '../apps/server/src/index.ts';

test('管理员可取消、确认和清空配对公开地址',async t=>{
  const dataDir=await mkdtemp(join(tmpdir(),'admin-network-')),token='synthetic-admin-network';
  const server=await startServer({dataDir,port:0,host:'127.0.0.1',token,demo:true});
  t.after(async()=>{await server.close();await rm(dataDir,{recursive:true,force:true});});
  const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE});
  t.after(()=>browser.close());
  const context=await browser.newContext(),base=server.url+'/api/v1/admin/';
  const code=await context.request.post(base+'setup-code',{headers:{authorization:'Bearer '+token},data:{}});
  assert.equal(code.status(),200);
  const setup=await context.request.post(base+'setup',{data:{code:(await code.json()).code,password:'synthetic-admin-password'}});
  assert.equal(setup.status(),200);
  const page=await context.newPage();
  await page.goto(server.url+'/admin.html');
  const panel=page.getByRole('region',{name:'网络设置'});
  await panel.getByRole('button',{name:'查看网络设置'}).click();
  const input=panel.getByRole('textbox',{name:'公开访问地址'}),target='https://pair.example.test:8443';
  await expect(input).toHaveValue('');
  await input.fill(target);
  await panel.getByRole('button',{name:'保存公开地址',exact:true}).click();
  await expect(panel.getByText(target,{exact:true})).toBeVisible();
  await panel.getByRole('button',{name:'取消',exact:true}).click();
  assert.equal((await (await context.request.get(base+'network')).json()).publicOrigin,'');
  await panel.getByRole('button',{name:'保存公开地址',exact:true}).click();
  await panel.getByRole('button',{name:'确认保存公开地址'}).click();
  await expect(panel.getByRole('status')).toContainText('已保存公开访问地址');
  await page.reload();await panel.getByRole('button',{name:'查看网络设置'}).click();
  await expect(input).toHaveValue(target);
  const devices=page.getByRole('region',{name:'浏览器设备'});
  await devices.getByRole('button',{name:'读取设备列表'}).click();
  await devices.getByRole('textbox',{name:'设备名称'}).fill('合成设备');
  await devices.getByRole('button',{name:'生成配对链接'}).click();
  const link=new URL(await devices.getByRole('textbox',{name:'一次性配对链接'}).inputValue());
  assert.equal(link.origin,target);
  assert.ok(link.hash.startsWith('#home?browserPair='));
  const qr=devices.getByRole('img',{name:'浏览器配对二维码'});
  await expect(qr).toBeVisible();
  const expectedQR=await QRCode.toDataURL(link.href,{width:240,margin:4,errorCorrectionLevel:'M'});
  assert.ok(await qr.getAttribute('src')===expectedQR);
  await input.fill('');await panel.getByRole('button',{name:'保存公开地址',exact:true}).click();
  await expect(panel.getByRole('status')).toContainText('已恢复使用当前浏览器地址');
  assert.equal((await (await context.request.get(base+'network')).json()).publicOrigin,'');
});
