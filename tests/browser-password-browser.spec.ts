import assert from 'node:assert/strict';
import test from 'node:test';
import {mkdtemp,rm} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {chromium,expect} from '@playwright/test';
import {startServer} from '../apps/server/src/index.ts';

test('浏览器密码在本地完成注册和登录，可仅撤销经密码签发的设备',{timeout:60000},async t=>{
  const dataDir=await mkdtemp(join(tmpdir(),'browser-password-ui-'));
  const root='fixture-workbench-owner',password='fixture-browser-connection';
  const server=await startServer({host:'127.0.0.1',port:0,dataDir,token:root,demo:true});
  t.after(async()=>{await server.close();await rm(dataDir,{recursive:true,force:true});});
  const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE});
  t.after(()=>browser.close());
  const admin=await browser.newContext(),ordinary=await browser.newContext();
  const requests:string[]=[];
  for(const ctx of [admin,ordinary])ctx.on('request',request=>{
    if(request.url().includes('/api/') && request.url().includes('password'))
      requests.push(request.url()+' '+(request.postData()??''));
  });
  const path=server.url+'/api/v1/admin';
  const issue=await admin.request.post(path+'/setup-code',{headers:{authorization:'Bearer '+root},data:{}});
  const setup=await admin.request.post(path+'/setup',{data:{code:(await issue.json()).code,password:'fixture-admin-pass'}});
  assert.equal(setup.status(),200);
  const csrf={'x-csrf-token':(await setup.json()).csrf};
  assert.equal((await admin.request.post(path+'/password-login/register/start',{data:{message:'sample',revision:'stale'}})).status(),403);
  const invite=await admin.request.post(path+'/devices/pairings',{data:{name:'链接配对设备'},headers:csrf});
  const paired=await (await ordinary.request.post(server.url+'/api/v1/public/browser-pair',{data:{code:(await invite.json()).code}})).json();
  const owner=await admin.newPage();await owner.goto(server.url+'/admin.html');
  const settings=owner.getByRole('region',{name:'浏览器密码登录'});
  await settings.getByRole('button',{name:'管理浏览器登录密码'}).click();
  await settings.getByLabel('浏览器登录密码',{exact:true}).fill(password);
  await settings.getByLabel('确认浏览器登录密码').fill(password);
  await settings.getByRole('button',{name:'保存浏览器登录密码'}).click();
  const publicState=async()=> (await (await ordinary.request.get(server.url+'/api/v1/public/password/state')).json()).enabled;
  await expect.poll(publicState).toBe(true);
  const page=await ordinary.newPage();await page.goto(server.url+'/#home');
  await expect(page.locator('#connection')).toContainText('需要令牌');
  await page.locator('#connection').click();
  await page.getByRole('button',{name:'使用浏览器密码登录'}).click();
  const dialog=page.getByRole('dialog',{name:'浏览器密码登录'});
  await dialog.getByLabel('设备名称').fill('密码登录设备');
  await dialog.getByLabel('浏览器登录密码').fill(password);
  await dialog.getByRole('button',{name:'登录工作台'}).click();
  await expect(page.locator('#connection')).toContainText('已连接',{timeout:12000});
  const listing=await (await admin.request.get(path+'/devices')).json();
  assert.deepEqual(listing.devices.map((item:{name:string})=>item.name).sort(),['密码登录设备','链接配对设备'].sort());
  await settings.getByLabel('同时撤销通过密码登录的设备').check();
  await settings.getByRole('button',{name:'停用浏览器密码登录'}).click();
  await owner.getByRole('button',{name:'确认停用'}).click();
  await expect.poll(publicState).toBe(false);
  await page.reload();await expect(page.locator('#connection')).toContainText('需要令牌');
  assert.equal((await ordinary.request.get(server.url+'/api/v1/projects',{headers:{authorization:'Bearer '+paired.token}})).status(),200);
  await settings.getByRole('button',{name:'重新启用浏览器密码登录'}).click();
  await expect.poll(publicState).toBe(true);
  const updatedPassword='fixture-replaced-connection';
  await settings.getByLabel('浏览器登录密码',{exact:true}).fill(updatedPassword);
  await settings.getByLabel('确认浏览器登录密码').fill(updatedPassword);
  const saved=owner.waitForResponse(r=>r.url().endsWith('/register/finish') && r.status()===200);
  await settings.getByRole('button',{name:'保存浏览器登录密码'}).click();await saved;
  await page.locator('#connection').click();
  await page.getByRole('button',{name:'使用浏览器密码登录'}).click();
  await dialog.getByLabel('设备名称').fill('更换密码后登录');
  await dialog.getByLabel('浏览器登录密码').fill(password);
  await dialog.getByRole('button',{name:'登录工作台'}).click();
  await expect(dialog.getByRole('button',{name:'登录工作台'})).toBeEnabled();
  await expect(dialog).toBeVisible();
  await dialog.getByLabel('浏览器登录密码').fill(updatedPassword);
  await dialog.getByRole('button',{name:'登录工作台'}).click();
  await expect(page.locator('#connection')).toContainText('已连接',{timeout:12000});
  assert.ok(requests.some(line=>line.includes('/register/finish')));
  assert.ok(requests.some(line=>line.includes('/public/password/finish')));
  assert.ok(requests.every(line=>!line.includes(password) && !line.includes(updatedPassword)));
});
