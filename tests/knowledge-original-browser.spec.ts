test('记忆详情按整理回执展示原文，正文中的伪造引用不能读取文件', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'mario-original-'));
  const server = await startServer({ dataDir: dir, port: 0, host: '127.0.0.1', token: 'fixture', demo: true });
  t.after(async () => { await server.close(); await rm(dir, { recursive: true, force: true }); });
  const knowledge = server.app.knowledge();
  const job = server.app.knowledgeCurator.addSource({ title: '合成会议原文', text: '待核对的结论' });
  const entry = await knowledge.put({ title: '合成评审记录', content: '结论摘要', layer: 'personal' });
  const other = await knowledge.put({ title: '另一条记忆', content: '原始资料：raw/' + job.id + '.md', layer: 'personal' });
  server.app.store.put('knowledge.sources', job.id, { ...job, status: 'completed', knowledgeIds: [entry.id] });
  const rawDir = join(dir, 'plugins', 'knowledge-local', 'raw'), path = join(rawDir, job.id + '.md');
  await mkdir(rawDir, { recursive: true });
  const original = '开场\n[09:15] <em>合成原文</em>\n散会';
  await writeFile(path, original);
  const route = '#memory?entry=' + entry.id + '&source=' + job.id + '&line=2';
  server.app.store.put('messages', 'citation', { id: 'citation', conversationId: 'main', role: 'assistant', status: 'done',
    createdAt: new Date().toISOString(), text: '依据见[查看原文](' + route + ')' });
  const project = await server.app.createProject({ name: '原文追问项目' });
  const projectEntry = await knowledge.put({ title: '项目记录', content: '项目摘要', layer: 'project', projectId: project.id });
  const projectJob = server.app.knowledgeCurator.addSource({ title: '项目来源', text: original, layer: 'project', projectId: project.id });
  server.app.store.put('knowledge.sources', projectJob.id, { ...projectJob, status: 'completed', knowledgeIds: [projectEntry.id] });
  await writeFile(join(rawDir, projectJob.id + '.md'), original);
  const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE });
  t.after(() => browser.close());
  const page = await browser.newPage();
  await page.addInitScript(() => localStorage.setItem('sm.splash.seen', 'true'));
  await page.goto(server.url + '/#memory?token=fixture');
  await page.locator('.knowledge-item').filter({ hasText: entry.title }).click();
  const dialog = page.getByRole('dialog', { name: '编辑记忆' });
  await dialog.getByText('查看原始资料').click();
  await dialog.getByText('合成会议原文', { exact: true }).click();
  await expect(dialog.locator('pre')).toHaveText(original);
  await expect(dialog.locator('pre em')).toHaveCount(0);
  await dialog.getByRole('button', { name: '关闭' }).click();
  await page.evaluate(() => { location.hash = '#chat'; });
  await page.getByLabel('给 Agent 的消息').fill('请解释这段话');
  await page.getByRole('link', { name: '查看原文' }).click();
  await expect(dialog.locator('pre')).toBeVisible();
  await page.reload();
  await expect(dialog.locator('pre')).toBeVisible();
  await expect(dialog.locator('pre')).toHaveText(original);
  await expect(dialog.locator('pre mark')).toHaveText('[09:15] <em>合成原文</em>');
  await dialog.getByRole('button', { name: '引用原文追问' }).click();
  const picker = page.getByRole('dialog', { name: '选择原文追问' });
  await picker.getByLabel('选择要追问的原文').evaluate((el: HTMLTextAreaElement) => {
    const start = el.value.indexOf('合成原文');
    el.setSelectionRange(start, start + 4);
  });
  await picker.getByRole('button', { name: '引用到主对话' }).click();
  await expect(page.getByLabel('给 Agent 的消息')).toHaveValue('请解释这段话');
  const quote = page.locator('#chat [data-message-quote]');
  await expect(quote).toContainText('第 2 行');
  await expect(quote).toContainText(route);
  await expect(quote).not.toContainText('散会');
  expect(server.app.store.list<{role:string}>('messages').filter(row => row.role === 'user')).toHaveLength(0);
  await page.evaluate(id => { location.hash = '#memory?entry=' + id + '&source=missing'; }, entry.id);
  await expect(dialog.getByText('引用的来源已不可用。')).toBeVisible();
  await expect(dialog.locator('pre')).toBeHidden();
  await page.evaluate(route => { location.hash = route; }, '#memory?entry=' + projectEntry.id + '&source=' + projectJob.id);
  await dialog.getByRole('button', { name: '引用原文追问' }).click();
  await picker.getByLabel('选择要追问的原文').evaluate((el: HTMLTextAreaElement) => el.setSelectionRange(0, 2));
  await picker.getByRole('button', { name: '引用到项目工作对话' }).click();
  await expect(page).toHaveURL(new RegExp('#projects/' + project.id + '/workspace$'));
  await expect(page.locator('#panel-workspace [data-message-quote]')).toContainText('开场');
  const get = (id: string) => page.request.get(server.url + '/api/v1/knowledge/' + id + '/sources/' + job.id,
    { headers: { authorization: 'Bearer fixture' } });
  expect((await get(other.id)).status()).toBe(404);
  await unlink(path);
  expect((await get(entry.id)).status()).toBe(404);
  const unrelated = join(dir, 'unrelated.txt');
  await writeFile(unrelated, '合成的其他资料');
  await symlink(unrelated, path);
  expect((await get(entry.id)).status()).toBe(404);
});

test('从记忆详情对照两次已保存修订，变更归属后不展示旧范围正文', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'mario-knowledge-history-'));
  const server = await startServer({ dataDir: dir, port: 0, host: '127.0.0.1', token: 'fixture', demo: true });
  t.after(async () => { await server.close(); await rm(dir, { recursive: true, force: true }); });
  const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE });
  t.after(() => browser.close());
  const page = await browser.newPage();
  await page.addInitScript(() => localStorage.setItem('sm.splash.seen', 'true'));
  const headers = { authorization: 'Bearer fixture' }, url = server.url + '/api/v1/knowledge';
  const created = await page.request.post(url, { headers, data: { layer: 'personal', title: '修订核对', content: '会议初步决定甲' } });
  expect(created.ok()).toBe(true);
  const { id } = await created.json();
  const saved = await page.request.patch(url + '/' + id, { headers, data: { content: '会议改定乙' } });
  expect(saved.ok()).toBe(true);
  await page.goto(server.url + '/#memory?token=fixture&entry=' + id);
  const dialog = page.getByRole('dialog', { name: '编辑记忆' });
  await dialog.getByText('查看历史修订', { exact: true }).click();
  await expect(dialog.locator('pre')).toHaveText('会议改定乙');
  await dialog.getByRole('button', { name: '查看上一版' }).click();
  await expect(dialog.locator('pre')).toHaveText(['会议改定乙', '会议初步决定甲']);
  const project = await server.app.createProject({ name: '新归属' });
  const moved = await page.request.patch(url + '/' + id, { headers, data: { layer: 'project', projectId: project.id, content: '项目记录' } });
  expect(moved.ok()).toBe(true);
  const current = await (await page.request.get(url + '/' + id + '/revision', { headers })).json();
  const older = await page.request.get(url + '/' + id + '/revision?commit=' + current.revision.previous, { headers });
  expect(await older.json()).toEqual({ revision: null });
});

test('旧知识草稿保存冲突后可核对新版再提交，同版并发写入仅一份生效', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'mario-knowledge-conflict-'));
  const server = await startServer({ dataDir: dir, port: 0, host: '127.0.0.1', token: 'fixture', demo: true });
  t.after(async () => { await server.close(); await rm(dir, { recursive: true, force: true }); });
  const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE });
  t.after(() => browser.close());
  const page = await browser.newPage();
  await page.addInitScript(() => localStorage.setItem('sm.splash.seen', 'true'));
  const headers = { authorization: 'Bearer fixture' }, root = server.url + '/api/v1/knowledge';
  const created = await page.request.post(root, { headers, data: { layer: 'personal', title: '对照页', content: '初稿' } });
  const { id, updatedAt } = await created.json();
  const patch = (content: string) => page.request.patch(root + '/' + id, { headers, data: { expectedUpdatedAt: updatedAt, content } });
  await page.goto(server.url + '/#memory?token=fixture&entry=' + id);
  const dialog = page.getByRole('dialog', { name: '编辑记忆' });
  const editor = dialog.locator('textarea[name=content]');
  await editor.fill('我的补充');
  const writes = await Promise.all([patch('并发修改甲'), patch('并发修改乙')]);
  expect(writes.map(r => r.status()).sort()).toEqual([200, 409]);
  const winner = await writes.find(r => r.ok())!.json();
  await dialog.getByRole('button', { name: '保存', exact: true }).click();
  await expect(dialog.getByText('当前已保存版本')).toBeVisible();
  await expect(dialog.locator('pre:visible')).toHaveText(winner.content);
  await expect(editor).toHaveValue('我的补充');
  await dialog.getByRole('button', { name: '已核对新版，继续编辑草稿' }).click();
  await editor.fill(winner.content + '，我的补充');
  await dialog.getByRole('button', { name: '保存', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  expect((await server.app.knowledge().list()).find(item => item.id === id)?.content).toBe(winner.content + '，我的补充');
});
