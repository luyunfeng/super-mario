import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import test from 'node:test';
import {chromium,expect} from '@playwright/test';
import {startServer} from '../apps/server/src/index.ts';

test('主对话标注、裁剪并旋转合成图片，重开可撤销；取消或停用后仍发送上次保存的像素', {timeout:60000}, async t=>{
  const dir=await mkdtemp(join(tmpdir(),'mario-edit-image-')),token='fixture-image-editor';
  const server=await startServer({host:'127.0.0.1',port:0,dataDir:dir,demo:true,token});
  t.after(async()=>{await server.close();await rm(dir,{recursive:true,force:true});});
  const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE});
  t.after(()=>browser.close());
  const page=await browser.newPage();
  await page.addInitScript(()=>localStorage.setItem('sm.splash.seen','true'));
  await page.goto(server.url+'/#chat?token='+token);
  const original=await page.evaluate(()=>{
    const c=document.createElement('canvas');c.width=320;c.height=160;
    const ctx=c.getContext('2d')!;
    ctx.fillStyle='rgb(180,180,180)';ctx.fillRect(0,0,160,160);
    ctx.fillStyle='white';ctx.fillRect(160,0,160,160);
    return c.toDataURL('image/png').split(',')[1]!;
  });
  await page.getByLabel('选择图片').setInputFiles({name:'合成图片.png',mimeType:'image/png',buffer:Buffer.from(original,'base64')});
  const edit=page.getByRole('button',{name:'编辑第 1 张图片',exact:true});
  const dialog=page.getByRole('dialog',{name:'编辑图片'}),canvas=dialog.locator('canvas');
  const button=(name:string)=>dialog.getByRole('button',{name,exact:true});
  const draft=page.locator('.message-image-draft img');
  await edit.click();
  await button('画笔').click();
  const box=await canvas.boundingBox();assert.ok(box);
  // The horizontal mark crosses the middle of the image and survives the centred square crop.
  await page.mouse.move(box.x+box.width*.45,box.y+box.height*.5);
  await page.mouse.down();
  await page.mouse.move(box.x+box.width*.55,box.y+box.height*.5,{steps:8});
  await page.mouse.up();
  await button('裁剪').click();
  await dialog.getByLabel('裁剪比例').selectOption('square');
  await button('向左旋转').click();
  await button('保存').click();
  await expect(dialog).toBeHidden();
  const saved=await draft.getAttribute('src');
  assert.ok(saved && !saved.endsWith(original));
  await page.reload();await expect(draft).toHaveAttribute('src',saved);
  await edit.click();
  const beforeUndo=await canvas.evaluate((el:HTMLCanvasElement)=>el.toDataURL());
  await button('撤销').click();
  await expect.poll(()=>canvas.evaluate((el:HTMLCanvasElement)=>el.toDataURL())).not.toBe(beforeUndo);
  await button('取消').click();
  await expect(draft).toHaveAttribute('src',saved);
  await edit.click();
  await button('撤销').click();
  const plugin=server.url+'/api/v1/plugins/conversation-images';
  const toggle=async(enabled:boolean)=>{
    const response=await page.request.post(plugin,{headers:{authorization:'Bearer '+token},data:{enabled}});
    assert.equal(response.status(),200,await response.text());
  };
  await toggle(false);await expect(dialog).toBeHidden();await expect(edit).toBeHidden();
  await toggle(true);await expect(edit).toBeVisible();
  await page.reload();await expect(draft).toHaveAttribute('src',saved);
  const url=server.url+'/api/v1/messages';
  const posted=page.waitForResponse(r=>r.url()===url && r.request().method()==='POST');
  await page.getByRole('button',{name:'发送',exact:true}).click();
  const response=await posted;assert.equal(response.status(),202,await response.text());
  const images=response.request().postDataJSON().images as {mime:string;data:string}[];
  assert.equal(images.length,1);
  const image=images[0]!;
  assert.ok(['image/png','image/webp'].includes(image.mime));
  const dataUrl='data:'+image.mime+';base64,'+image.data;
  assert.equal(dataUrl,saved);
  const receipt=await response.json();
  assert.equal(receipt.images[0].sha256,createHash('sha256').update(Buffer.from(image.data,'base64')).digest('hex'));
  const actual=await page.evaluate(async url=>{
    const img=new Image();img.src=url;await img.decode();
    const c=document.createElement('canvas');c.width=img.naturalWidth;c.height=img.naturalHeight;
    const ctx=c.getContext('2d')!;ctx.drawImage(img,0,0);
    const rgba=(x:number,y:number)=>[...ctx.getImageData(Math.floor(c.width*x),Math.floor(c.height*y),1,1).data];
    const area=ctx.getImageData(c.width*.2,c.height*.2,c.width*.6,c.height*.6).data;
    let ink=0;
    for(let i=0;i<area.length;i+=4)if(Math.min(area[i]!,area[i+1]!,area[i+2]!)<145)ink++;
    return {w:c.width,h:c.height,top:rgba(.2,.2),bottom:rgba(.2,.8),ink};
  },dataUrl);
  assert.deepEqual([actual.w,actual.h],[160,160]);
  assert.ok(actual.top.slice(0,3).every(v=>v>245),'左转后上方应为原图右侧白色');
  assert.ok(actual.bottom.slice(0,3).every(v=>Math.abs(v-180)<10),'左转后下方应为原图左侧灰色');
  assert.ok(actual.ink>5,'标注须进入服务端实际接收的像素');
});
