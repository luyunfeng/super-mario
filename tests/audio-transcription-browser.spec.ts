import test from 'node:test';
import { createServer } from 'node:http';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium, expect } from '@playwright/test';
import { startServer } from '../apps/server/src/index.ts';

test('录音经认证服务转写后追加到当前草稿，失败和切换项目保留草稿', async t => {
  const calls: { model: unknown; file: string; audio: string; auth?: string }[] = [];
  let finish: (() => void) | undefined;
  const upstream = createServer(async (req, res) => {
    const chunks = [];
    for await (const chunk of req) chunks.push(chunk);
    const form = await new Response(Buffer.concat(chunks), { headers: { 'content-type': req.headers['content-type']! } }).formData();
    const file = form.get('file') as File;
    calls.push({ model: form.get('model'), file: file.name, audio: await file.text(), auth: req.headers.authorization });
    if (calls.length === 2) await new Promise<void>(resolve => { finish = resolve; });
    res.end(JSON.stringify({ text: '合成转写' }));
  });
  await new Promise<void>(resolve => upstream.listen(0, '127.0.0.1', resolve));
  t.after(() => { finish?.(); upstream.closeAllConnections(); upstream.close(); });
  const address = upstream.address();
  if (!address || typeof address === 'string') throw new Error('转写测试服务未监听');
  const keys = ['SUPER_MARIO_TRANSCRIPTION_URL', 'SUPER_MARIO_TRANSCRIPTION_MODEL', 'SUPER_MARIO_TRANSCRIPTION_API_KEY'];
  const previous = keys.map(k => process.env[k]);
  t.after(() => keys.forEach((k, i) => { if (previous[i] === undefined) delete process.env[k]; else process.env[k] = previous[i]; }));
  delete process.env.SUPER_MARIO_TRANSCRIPTION_URL;
  process.env.SUPER_MARIO_TRANSCRIPTION_MODEL = 'fixture-model';
  process.env.SUPER_MARIO_TRANSCRIPTION_API_KEY = 'fixture-key';
  const dir = await mkdtemp(join(tmpdir(), 'mario-transcription-'));
  const server = await startServer({ dataDir: dir, port: 0, host: '127.0.0.1', token: 'fixture', demo: true });
  t.after(async () => { await server.close(); await rm(dir, { recursive: true, force: true }); });
  const project = await server.app.createProject({ name: '转写项目' });
  const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE });
  t.after(() => browser.close());
  const page = await browser.newPage({ timezoneId: 'Asia/Kathmandu' });
  await page.addInitScript(() => {
    localStorage.setItem('sm.splash.seen', 'true');
    Object.assign(window, { SpeechRecognition: undefined, webkitSpeechRecognition: undefined });
    navigator.mediaDevices.getUserMedia = async () => {
      const context = new AudioContext();
      const tone = context.createOscillator(), output = context.createMediaStreamDestination();
      tone.connect(output); tone.start();
      await context.resume();
      Object.assign(window, { capturedTrack: output.stream.getAudioTracks()[0] });
      if (document.body.dataset.delayGrant)
        await new Promise<void>(resolve => window.addEventListener('grant-microphone', () => resolve(), { once: true }));
      return output.stream;
    };
    const NativeRecorder = MediaRecorder;
    window.MediaRecorder = class extends NativeRecorder {
      constructor(stream: MediaStream, options?: MediaRecorderOptions) {
        super(stream, options);
        const now = new Date();
        document.body.dataset.captureTime = new Date(now.getTime() - now.getTimezoneOffset() * 60000).toISOString().slice(0, 16);
        this.addEventListener('dataavailable', e => { if (e.data.size) document.body.dataset.audioReady = 'yes'; });
      }
    };
  });
  await page.goto(server.url + '/#chat?token=fixture');
  const upload = async () => {
    const chooser = page.waitForEvent('filechooser');
    await page.getByRole('button', { name: '录音转文字' }).click();
    await (await chooser).setFiles({ name: 'sample.wav', mimeType: 'audio/wav', buffer: Buffer.from('offline-audio') });
  };
  const input = page.getByLabel('给 Agent 的消息');
  await input.fill('原文');
  await upload();
  await expect(page.getByText(/转写失败：.*SUPER_MARIO_TRANSCRIPTION_URL/)).toBeVisible();
  await expect(input).toHaveValue('原文');
  process.env.SUPER_MARIO_TRANSCRIPTION_URL = 'http://127.0.0.1:' + address.port + '/transcriptions';
  await page.getByRole('button', { name: '重试转写' }).click();
  await expect(input).toHaveValue('原文合成转写');
  const organize = page.getByRole('button', { name: '整理会议转写' });
  const review = page.getByRole('dialog', { name: '核对会议转写' });
  await organize.click();
  await expect(review).toContainText('保存到个人记忆');
  await expect(review.getByLabel('转写正文')).toHaveValue('合成转写');
  await review.getByRole('button', { name: '关闭' }).click();
  expect(server.app.knowledgeCurator.status().jobs).toHaveLength(0);
  expect(calls).toEqual([{ model: 'fixture-model', file: 'audio.wav', audio: 'offline-audio', auth: 'Bearer fixture-key' }]);
  await upload();
  await expect.poll(() => calls.length).toBe(2);
  await page.evaluate(id => { location.hash = '#projects/' + id + '/workspace'; }, project.id);
  const work = page.getByLabel('项目目标');
  await expect(work).toBeEditable();
  finish!();
  await upload();
  await expect(work).toHaveValue('合成转写');
  await organize.click();
  await expect(review).toContainText('保存到项目记忆 · 转写项目');
  await expect(review.getByLabel('会议开始时间（可选）')).toHaveValue('');
  await expect(review.getByLabel('会议时区（UTC 偏移）')).toBeDisabled();
  await review.getByLabel('会议开始时间（可选）').fill('2032-02-29T00:10');
  await review.getByLabel('会议时区（UTC 偏移）').fill('+24:00');
  await review.getByRole('button', { name: '提交会议整理' }).click();
  await expect(review.getByRole('status')).toContainText('请核对会议日期');
  expect(server.app.knowledgeCurator.status().jobs).toHaveLength(0);
  await review.getByLabel('会议时区（UTC 偏移）').fill('+05:45');
  await review.getByLabel('会议标题').fill('合成评审');
  await review.getByLabel('转写正文').fill('会中提议复核，负责人待确认。');
  await review.getByRole('button', { name: '提交会议整理' }).click();
  await expect(review).toHaveCount(0);
  const jobs = server.app.knowledgeCurator.status().jobs;
  expect(jobs).toHaveLength(1);
  expect(server.app.store.get<{ text: string }>('knowledge.sources', jobs[0].id)?.text).toBe('会中提议复核，负责人待确认。');
  expect(jobs[0]).toMatchObject({ title: '合成评审', meetingStartedAt: '2032-02-29T00:10:00+05:45', materialKind: 'meeting-transcript', projectId: project.id, layer: 'project', status: 'queued' });
  await expect(work).toHaveValue('合成转写');
  const record = page.getByRole('button', { name: '录音后转写' });
  await record.click();
  await expect(page.locator('body')).toHaveAttribute('data-audio-ready', 'yes');
  const paused = page.getByRole('button', { name: '继续录音' });
  const pause = page.getByRole('button', { name: '暂停录音' });
  const micEnabled = () => page.evaluate(() => (window as unknown as { capturedTrack: MediaStreamTrack }).capturedTrack.enabled);
  await pause.click();
  expect(await micEnabled()).toBe(false);
  await paused.click();
  expect(await micEnabled()).toBe(true);
  await pause.click();
  expect(calls).toHaveLength(3);
  await page.getByRole('button', { name: '结束并转写' }).click();
  await expect(work).toHaveValue('合成转写合成转写');
  expect(calls.at(-1)?.file).toBe('audio.webm');
  await organize.click();
  await expect(review.getByLabel('会议开始时间（可选）')).toHaveValue((await page.locator('body').getAttribute('data-capture-time'))!);
  await expect(review.getByLabel('会议时区（UTC 偏移）')).toHaveValue('+05:45');
  await review.getByRole('button', { name: '关闭' }).click();
  const trackState = () => page.evaluate(() => (window as unknown as { capturedTrack: MediaStreamTrack }).capturedTrack.readyState);
  expect(await trackState()).toBe('ended');
  await record.click();
  await expect(page.getByRole('button', { name: '结束并转写' })).toBeVisible();
  await page.evaluate(() => { location.hash = '#home'; });
  await expect.poll(trackState).toBe('ended');
  await page.evaluate(() => { location.hash = '#chat'; document.body.dataset.delayGrant = 'yes'; });
  await record.click();
  await expect.poll(trackState).toBe('live');
  await page.getByRole('button', { name: '取消录音' }).click();
  await page.evaluate(() => window.dispatchEvent(new Event('grant-microphone')));
  await expect.poll(trackState).toBe('ended');
  const path = server.url + '/api/v1/audio-transcription';
  const headers = { authorization: 'Bearer fixture' };
  expect((await page.request.post(path, { data: {} })).status()).toBe(401);
  expect((await page.request.post(path, { headers, data: { format: 'wav', audio: '%%%' } })).status()).toBe(400);
  const disabled = await page.request.post(server.url + '/api/v1/plugins/voice-input', { headers, data: { enabled: false } });
  expect(disabled.ok()).toBe(true);
  await expect(page.getByRole('button', { name: '录音转文字' })).toHaveCount(0);
  expect((await page.request.post(path, { headers, data: {} })).status()).toBe(503);
  expect(calls).toHaveLength(4);
});
