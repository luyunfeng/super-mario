import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { imageSize } from 'image-size';
import { createRequire } from 'node:module';
import JSZip from 'jszip';
import { readChatFilePreview } from '../plugins/chat-file-preview.ts';

test('预览取 PDF 真正首页及包内真实图像，缺图时提取有来源的文本',async t=>{
  const dir=await mkdtemp(join(tmpdir(),'mario-file-preview-'));
  t.after(()=>rm(dir,{recursive:true,force:true}));
  const get=async(name:string,bytes:Buffer,signal=new AbortController().signal)=>{
    const path=join(dir,name);await writeFile(path,bytes);
    return readChatFilePreview(path,{name,bytes:bytes.length,mime:'application/octet-stream',sha256:'synthetic'},signal);
  };
  const fixture=(name:string)=>readFile(new URL('./fixtures/knowledge-attachments/'+name,import.meta.url));
  const pdf=await get('样本.pdf',await fixture('text-layer.pdf'));
  assert.equal(pdf.thumbnail?.mime,'image/png');assert.match(pdf.note!,/PDF 首页/);
  const image=Buffer.from(pdf.thumbnail!.data,'base64');
  const {width,height,type}=imageSize(image);
  assert.ok(width && height && Math.max(width,height)<=720);assert.equal(type,'png');
  const rgba:Buffer=createRequire(import.meta.url)('pngjs').PNG.sync.read(image).data;
  assert.ok(rgba.some((v,i)=>i%4<3 && v<120),'首页确实绘出了内容');
  const office=await JSZip.loadAsync(await fixture('basic.docx'));
  office.file('docProps/thumbnail.png',image);
  assert.match((await get('文档.docx',await office.generateAsync({type:'nodebuffer'}))).note!,/内嵌预览/);
  office.file('docProps/thumbnail.png','<svg onload="alert(1)"></svg>');
  const fallback=await get('无图.docx',await office.generateAsync({type:'nodebuffer'}));
  assert.equal(fallback.thumbnail,undefined);assert.match(fallback.text!,/G21 DOCX 中文测试/);assert.match(fallback.note!,/文字摘录/);
  const iwork=new JSZip();
  iwork.file('index.xml','<doc xmlns:sf="http://developer.apple.com/namespaces/sf"><sf:p>真实段落</sf:p></doc>');
  iwork.file('QuickLook/Thumbnail.png',image);
  assert.ok((await get('样本.pages',await iwork.generateAsync({type:'nodebuffer'}))).thumbnail);
  iwork.remove('QuickLook/Thumbnail.png');
  iwork.file('QuickLook/Preview.pdf',await fixture('text-layer.pdf'));
  assert.match((await get('内嵌文档.pages',await iwork.generateAsync({type:'nodebuffer'}))).note!,/内嵌 PDF/);
  iwork.remove('QuickLook/Preview.pdf');assert.match((await get('旧版.pages',await iwork.generateAsync({type:'nodebuffer'}))).text!,/真实段落/);
  iwork.remove('index.xml');iwork.file('Index/Document.iwa','private binary never show');
  const unavailable=await get('新版.key',await iwork.generateAsync({type:'nodebuffer'}));
  assert.ok(!unavailable.text && !unavailable.thumbnail); assert.match(unavailable.note!,/没有可读取/);
  const rtf=await get('简单.rtf',Buffer.from('{\\rtf1\\ansi Title\\par \\u20013?}'));
  assert.equal(rtf.text,'Title\n中');
  const field=await get('字段.rtf',Buffer.from('{\\rtf1{\\field{\\*\\fldinst HYPERLINK "https://example.invalid/"}}}'));
  assert.ok(!field.text);assert.doesNotMatch(field.note!,/example.invalid/);
  const clipped=await get('长摘录.txt',Buffer.from('长'.repeat(6600)));
  assert.equal(clipped.truncated,true);assert.equal(clipped.text!.length,6000);
  const controller=new AbortController();
  const task=get('中止.pdf',await fixture('text-layer.pdf'),controller.signal);
  setTimeout(()=>controller.abort(),10);
  await assert.rejects(task,{name:'AbortError'});
});
