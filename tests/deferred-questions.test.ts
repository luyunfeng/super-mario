test('过期提问转待办，重启补建，显式回答与手工决定同一目标仅受理一次',async t=>{
  const dataDir=await mkdtemp(join(tmpdir(),'deferred-question-'));
  const config={dataDir,host:'127.0.0.1',port:0,demo:true,token:'fixture'};
  let server=await startServer(config);
  t.after(async()=>{await server.close();await rm(dataDir,{recursive:true,force:true});});
  const request=(path:string,body:unknown,method='POST')=>fetch(server.url+'/api/v1'+path,{
    method,headers:{authorization:'Bearer fixture','content-type':'application/json'},body:JSON.stringify(body)});
  const ask=async(label:string)=>{
    const res=await request('/messages',{text:'合成原目标-'+label});
    const input=await res.json() as Message;
    const card=server.app.interactions.open({kind:'question',title:'待决定-'+label,body:'保留甲或乙？'},input);
    return {card,input};
  };
  const expire=async(label:string)=>{
    const {card,input}=await ask(label);
    server.app.interactions.expireTick(Date.parse(card.expiresAt)+1);
    const todo=server.app.todos().find(todo=>todo.deferredQuestion?.cardId===card.id)!;
    assert.ok(todo);
    return {todo,card,input};
  };
  server.app.policies.write({},{ladder:['user']});
  const first=await ask('升级');
  const oldOpen=server.app.interactions.open({kind:'question',title:'重启前超过截止时间',body:'旧卡'});
  await server.close();
  const db=createStore(join(dataDir,'workbench.sqlite'));
  db.put('interactions',first.card.id,{...first.card,status:'expired',expiresAt:new Date(Date.now()-1000).toISOString()});
  db.put('interactions',oldOpen.id,{...oldOpen,expiresAt:new Date(Date.now()-1000).toISOString()});
  db.remove('messages','interaction-notice:'+oldOpen.id);
  db.close();
  server=await startServer(config);
  assert.equal(server.app.store.get('messages','interaction-notice:'+oldOpen.id),undefined);
  const a=server.app.todos().find(todo=>todo.deferredQuestion?.cardId===first.card.id)!;
  assert.equal(a.notes,first.card.body);
  assert.deepEqual(a.deferredQuestion,{cardId:first.card.id,askedAt:first.card.createdAt,title:first.card.title,body:first.card.body});
  const patch=(id:string,data:unknown)=>request('/todos/'+id,data,'PATCH');
  assert.equal((await patch(a.id,{notes:'被修改的备注，不是原问题'})).status,200);
  const project=server.app.projects.create({name:'其他项目'});
  assert.equal((await patch(a.id,{projectId:project.id})).status,409);
  assert.equal((await patch(a.id,{deferredQuestion:{cardId:'forged'}})).status,400);
  assert.equal((await request('/todos',{title:'伪造来源',deferredQuestion:{cardId:'forged'}})).status,400);
  const answer=(id:string,text:string)=>request('/todos/'+id+'/question-answer',{text});
  assert.equal((await answer(a.id,' ')).status,400);
  const replies=await Promise.all([answer(a.id,'采用乙'),answer(a.id,'采用乙')]);
  assert.deepEqual(replies.map(r=>r.status),[200,200]);
  const receipt=await replies[0]!.json();
  assert.deepEqual(await replies[1]!.json(),receipt);
  const messages=()=>server.app.store.list<Message>('messages');
  const delivered=messages().find(m=>m.id===receipt.messageId)!;
  assert.equal(delivered.conversationId,first.input.conversationId);
  assert.match(delivered.text,/合成原目标-升级/);
  assert.match(delivered.text,/保留甲或乙/);
  assert.doesNotMatch(delivered.text,/被修改的备注/);
  assert.equal(messages().filter(m=>m.role==='user' && m.text.includes('主人已回答此前过期')).length,1);
  assert.ok(server.app.todos().find(t=>t.id===a.id)?.completedAt);
  assert.equal((await answer(a.id,'与前次不同')).status,409);
  assert.equal((await patch(a.id,{completed:false})).status,409);
  const b=await expire('手填决定');
  const decision=await request('/todos/'+b.todo.id+'/decisions',{text:'使用丙'});
  assert.equal(decision.status,201);
  await t.waitFor(()=>assert.ok(server.app.todos().find(t=>t.id===b.todo.id)?.completedAt));
  assert.ok(messages().some(m=>m.text.includes('使用丙') && m.text.includes('待决定-手填决定')));
  const c=await expire('手工关闭');
  assert.equal((await patch(c.todo.id,{completed:true})).status,200);
  await t.waitFor(()=>assert.ok(messages().some(m=>m.text.includes('未提供答案') && m.text.includes(c.todo.id) && m.readOnly && m.origin==='notification')));
  assert.equal((await answer(c.todo.id,'迟到')).status,409);
  const race=await expire('同时关闭和回答');
  const pending=server.app.answerDeferredQuestion(race.todo.id,'不得虚报');
  server.app.updateTodo(race.todo.id,{completed:true},true);
  await assert.rejects(pending,{status:409});
  assert.ok(!messages().some(m=>m.text.includes('不得虚报')));
  const late=await ask('点击时已经超时');
  server.app.store.put('interactions',late.card.id,{...late.card,expiresAt:new Date(Date.now()-1000).toISOString()});
  assert.equal((await request('/interactions/'+late.card.id+'/answer',{version:late.card.version,text:'迟到'})).status,409);
  assert.ok(server.app.todos().some(t=>t.deferredQuestion?.cardId===late.card.id));
  const standalone=server.app.interactions.open({kind:'question',title:'无主人来源',body:'合成'});
  const internal=await server.app.agent.post('合成系统任务','main');
  const synthetic=server.app.interactions.open({kind:'question',title:'内部调用',body:'合成'},internal);
  server.app.interactions.expireTick(Math.max(Date.parse(standalone.expiresAt),Date.parse(synthetic.expiresAt))+1);
  assert.ok(!server.app.todos().some(t=>[standalone.id,synthetic.id].includes(t.deferredQuestion?.cardId??'')));
  const held=await expire('受理前拒绝');
  const realPost=server.app.agent.post;
  server.app.agent.post=async()=>{throw Object.assign(new Error('测试替身：暂时不能受理'),{status:503});};
  try {
    assert.equal((await answer(held.todo.id,'重启后恢复')).status,503);
    assert.equal((await answer(held.todo.id,'不同内容')).status,409);
    assert.ok(!server.app.todos().find(t=>t.id===held.todo.id)?.completedAt);
  } finally {server.app.agent.post=realPost;}
  const old=server.app.todos().find(t=>t.id===a.id)!;
  server.app.store.put('todos',a.id,{...old,deferredQuestion:{askedAt:first.card.createdAt,cardId:first.card.id}});
  await server.close();server=await startServer(config);
  assert.equal(server.app.todos().find(t=>t.id===a.id)?.deferredQuestion?.body,first.card.body);
  await t.waitFor(()=>assert.ok(server.app.todos().find(t=>t.id===held.todo.id)?.completedAt));
  assert.equal(messages().filter(m=>m.role==='user' && m.text.includes('重启后恢复')).length,1);
  assert.equal((await answer(a.id,'采用乙')).status,200);
  assert.equal(server.app.todos().filter(t=>t.deferredQuestion?.cardId===first.card.id).length,1);
});

test('过期的飞书独立私聊问题保留原会话与配对，移除绑定后拒绝答案',async t=>{
  const dataDir=await mkdtemp(join(tmpdir(),'deferred-private-'));
  let client!:FeishuOptions;
  const server=await startServer({dataDir,host:'127.0.0.1',port:0,demo:true,token:'fixture'},{botFactory:options=>{
    client=options;
    return {async start(){},async close(){},async collect(){return [];},status:()=>({connected:true}),async send(){}};
  }});
  t.after(async()=>{await server.close();await rm(dataDir,{recursive:true,force:true});});
  const {app}=server;
  app.policies.write({},{ladder:['user']});
  const bot=await server.bots.create({appId:'cli_1111111111111111',appSecret:'synthetic',name:'测试',scope:{kind:'global'},requireConfirmation:false});
  let count=0;
  const speak=(text:string)=>client.onMessage(text,{messageId:'om-'+ ++count,chatId:'p2p-fixture',senderId:'owner-fixture',senderType:'user',chatType:'p2p'});
  await speak(bot.pairingCode!); await speak('/new 合成问题');
  async function expired(text:string) {
    await speak(text);
    const source=app.store.list<Message>('messages').find(m=>m.role==='user' && m.text===text)!;
    assert.match(source.conversationId,/:thread:/);
    const card=app.interactions.open({kind:'question',title:'合成问题',body:'甲或乙'},source);
    app.interactions.expireTick(Date.parse(card.expiresAt)+1);
    return {source,todo:app.todos().find(t=>t.deferredQuestion?.cardId===card.id)!};
  }
  const {source,todo}=await expired('原私聊中的第一项');
  await speak('/main');
  const receipt=await app.answerDeferredQuestion(todo.id,'已选甲');
  const delivered=app.store.get<Message>('messages',receipt.messageId)!;
  assert.equal(delivered.conversationId,source.conversationId);
  assert.deepEqual(app.store.get('message.routes',delivered.id),{...app.store.get<object>('message.routes',source.id),resumed:true});
  await speak('/new 另一段私聊');
  const later=await expired('原私聊中的第二项');
  await server.bots.update(bot.id,{enabled:false});
  await assert.rejects(app.answerDeferredQuestion(later.todo.id,'无法回到旧配对'),{status:409});
  assert.ok(!app.todos().find(t=>t.id===later.todo.id)?.completedAt);
});
