import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {mkdtemp,readFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import test from 'node:test';
import {chromium,expect} from '@playwright/test';
import {startServer} from '../apps/server/src/index.ts';

test('独立 Web 对话按原项目与会话导出归档历史，下载内容与预览相同',{timeout:30000},async t=>{
  const dir=await mkdtemp(join(tmpdir(),'export-web-thread-')),token='synthetic-web-export';
  const server=await startServer({dataDir:dir,host:'127.0.0.1',port:0,token,demo:true});
  const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE});
  t.after(async()=>{await browser.close();await server.close();await rm(dir,{recursive:true,force:true});});
  const page=await browser.newPage(),project=server.app.projects.create({name:'导出验收项目'});
  const headers={authorization:'Bearer '+token,'content-type':'application/json'};
  const make=async(title:string,text:string)=>{
    const id=randomUUID(),path=server.url+'/api/v1/web-conversations';
    const registered=await fetch(path,{method:'POST',headers,body:JSON.stringify({id,title,projectId:project.id})});
    assert.equal(registered.status,201);
    const sent=await fetch(path+'/'+id+'/messages',{method:'POST',headers:{...headers,'Idempotency-Key':randomUUID()},body:JSON.stringify({text})});
    assert.equal(sent.status,202);return id;
  };
  const mine='仅在甲线的合成核对意见',foreign='其他线专用的合成标记';
  const first=await make('合成导出线',mine),second=await make('对照导出线',foreign);
  const path=server.url+'/api/v1/web-conversations/'+first;
  const original=await (await fetch(path,{headers})).json();
  const archived=await fetch(path,{method:'PATCH',headers,body:JSON.stringify({version:original.version,archived:true})});
  assert.equal(archived.status,200);
  await page.goto(server.url+'/#chat?thread='+first+'&token='+token);
  const region=page.getByLabel('独立对话内容'),action=region.getByRole('button',{name:'导出对话',exact:true});
  await expect(region).toContainText('已归档');
  const post=page.waitForRequest(req=>req.url().endsWith('/conversation-export') && req.method()==='POST');
  await action.click();
  assert.deepEqual((await post).postDataJSON(),{webThreadId:first,projectId:project.id,includeWork:false});
  const drawer=page.getByRole('dialog',{name:'导出对话',exact:true}),preview=drawer.getByLabel('Markdown 预览');
  await expect(preview).toContainText(mine);await expect(preview).not.toContainText(foreign);
  const markdown=await preview.textContent();
  const ready=page.waitForEvent('download');await drawer.getByRole('button',{name:'下载 .md'}).click();
  const file=await ready;assert.match(file.suggestedFilename(),/\.md$/);assert.equal(await readFile((await file.path())!,'utf8'),markdown);
  await page.goto(server.url+'/#chat?thread='+second);
  await expect(drawer).toHaveCount(0);await expect(region.getByRole('heading',{name:'对照导出线'})).toBeVisible();
  await action.click();await expect(preview).toContainText(foreign);await expect(preview).not.toContainText(mine);
  const firstMeta=await (await fetch(path,{headers})).json();
  await page.goto(server.url+'/#chat?thread='+first);
  await expect(drawer).toHaveCount(0);await action.click();await expect(preview).toContainText(mine);
  const removed=await fetch(path,{method:'DELETE',headers,body:JSON.stringify({version:firstMeta.version})});
  assert.equal(removed.status,200);await expect(drawer).toHaveCount(0);await expect(action).toHaveCount(0);
  await page.goto(server.url+'/#chat?thread='+second);await action.click();await expect(preview).toContainText(foreign);
  const disabled=await fetch(server.url+'/api/v1/plugins/conversation-export',{method:'POST',headers,body:JSON.stringify({enabled:false})});
  assert.equal(disabled.status,200);await expect(drawer).toHaveCount(0);await expect(action).toHaveCount(0);
});
