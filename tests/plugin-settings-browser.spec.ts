import test from 'node:test';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium, expect } from '@playwright/test';
import { startServer } from '../apps/server/src/index.ts';

test('从插件配置固定入口，刷新、停用与恢复，并从窄屏打开功能', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'mario-plugin-settings-'));
  const server = await startServer({ host: '127.0.0.1', port: 0, dataDir: dir, demo: true });
  const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE });
  t.after(async () => { await browser.close(); await server.close(); await rm(dir, { recursive: true, force: true }); });
  const page = await browser.newPage();
  await page.goto(server.url);
  const settings = page.getByRole('button', { name: '插件配置', exact: true });
  const dialog = page.getByRole('dialog', { name: '插件配置' });
  const plugin = dialog.locator('section').filter({ has: page.getByRole('button', { name: '主机器人配置' }) });
  const pin = page.getByRole('navigation', { name: '已固定的插件功能' }).getByRole('link', { name: '主机器人配置' });
  await page.goto(server.url + '/#agent');
  await page.locator('#agent-advanced > summary').click();
  await page.getByRole('button', { name: '打开插件配置' }).click();
  await dialog.getByRole('button', { name: '编辑 JSON' }).click();
  await dialog.getByLabel('JSON 配置').fill('{"defaultDays":30,"sessionLimit":8}');
  await dialog.getByRole('button', {name:'保存设置'}).click();
  await expect(dialog.getByRole('status')).toHaveText('设置已保存');
  await dialog.getByLabel('搜索插件').fill('feishu');
  await plugin.getByRole('checkbox').check();
  await dialog.getByRole('button', { name: '关闭' }).click();
  await pin.click();
  await expect(page).toHaveURL(/#channels\/main-bot$/);
  await page.reload();
  await expect(pin).toBeVisible();
  await settings.click();
  await dialog.getByLabel('搜索插件').fill('feishu');
  await plugin.getByRole('button', { name: '停用' }).click();
  await expect(plugin.getByRole('button', { name: '主机器人配置' })).toBeDisabled();
  await expect(pin).toHaveCount(0);
  await plugin.getByRole('button', { name: '启用' }).click();
  await expect(plugin.getByRole('button', { name: '主机器人配置' })).toBeEnabled();
  await dialog.getByRole('button', { name: '关闭' }).click();
  await expect(pin).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await settings.click();
  await dialog.getByLabel('搜索插件').fill('feishu');
  await plugin.getByRole('checkbox').uncheck();
  await plugin.getByRole('button', { name: '主机器人配置' }).click();
  await expect(dialog).toHaveCount(0);
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test('阅读字体与字号独立保存，窄屏可用，停用后还原默认样式', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'mario-reading-fonts-'));
  const server = await startServer({ host: '127.0.0.1', port: 0, dataDir: dir, demo: true });
  const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE });
  t.after(async () => { await browser.close(); await server.close(); await rm(dir, { recursive: true, force: true }); });
  const page = await browser.newPage();
  await page.goto(server.url);
  const dialog = page.getByRole('dialog', { name: '插件配置' });
  async function openFonts() {
    await page.getByRole('button', { name: '插件配置', exact: true }).click();
    await dialog.getByLabel('搜索插件').fill('阅读字体');
  }
  const bodyFont = () => page.evaluate(() => getComputedStyle(document.body).fontFamily);
  const codeFont = () => dialog.locator('code').evaluate(el => getComputedStyle(el).fontFamily);
  await openFonts();
  const originalBody = await bodyFont(), originalCode = await codeFont();
  const size = dialog.getByRole('combobox', { name: '阅读字号' });
  const pixels = () => page.evaluate(() => [document.body, document.querySelector('#message-text')!, document.querySelector('dialog section code')!]
    .map(el => Number.parseFloat(getComputedStyle(el).fontSize)));
  const standard = await pixels();
  expect(standard).toEqual([14, 14, 13]);
  const expectedSize = (ratio: number) => standard.map(n => Math.round(n * ratio * 100) / 100);
  const measured = async () => (await pixels()).map(n => Math.round(n * 100) / 100);
  await size.selectOption('large');
  await dialog.getByLabel('正文字体').fill('Georgia');
  await dialog.getByLabel('代码字体').fill('fixture, invalid');
  await dialog.getByRole('button', { name: '保存字体' }).click();
  await expect(dialog.getByRole('status')).toContainText('单个字体名称');
  await expect.poll(bodyFont).toBe(originalBody);
  await dialog.getByLabel('代码字体').fill('Fixture Mono');
  await dialog.getByRole('button', { name: '保存字体' }).click();
  await expect.poll(bodyFont).toMatch(/^Georgia,/);
  await expect.poll(measured).toEqual(expectedSize(14 / 13));
  await expect.poll(codeFont).toMatch(/^"Fixture Mono",/);
  await page.reload();
  await openFonts();
  await expect(dialog.getByLabel('代码字体')).toHaveValue('Fixture Mono');
  await expect(size).toHaveValue('large');
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await dialog.getByRole('button', { name: '停用' }).click();
  await expect.poll(bodyFont).toBe(originalBody);
  await expect.poll(codeFont).toBe(originalCode);
  await expect.poll(measured).toEqual(standard);
  await dialog.getByRole('button', { name: '启用' }).click();
  await expect.poll(bodyFont).toMatch(/^Georgia,/);
  await expect.poll(measured).toEqual(expectedSize(14 / 13));
  await size.selectOption('small');
  await dialog.getByLabel('正文字体').fill('');
  await dialog.getByRole('button', { name: '保存字体' }).click();
  await expect.poll(bodyFont).toBe(originalBody);
  await expect.poll(codeFont).toMatch(/^"Fixture Mono",/);
  await expect.poll(measured).toEqual(expectedSize(12 / 13));
  await size.selectOption('standard');
  await dialog.getByRole('button', { name: '保存字体' }).click();
  await expect.poll(measured).toEqual(standard);
});
