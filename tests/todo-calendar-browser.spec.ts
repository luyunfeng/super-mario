import assert from 'node:assert/strict';
import test from 'node:test';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium, expect } from '@playwright/test';
import { startServer } from '../apps/server/src/index.ts';
import type { Todo } from '../packages/protocol/src/index.ts';

test('项目待办日历按本地日期展示，支持改期、按时段新增和返回列表', { timeout: 60000 }, async t => {
  const dataDir = await mkdtemp(join(tmpdir(), 'mario-calendar-'));
  const server = await startServer({ dataDir, demo: true, host: '127.0.0.1', port: 0 });
  const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE });
  t.after(async () => {
    await browser.close();
    await server.close();
    await rm(dataDir, { recursive: true, force: true });
  });
  const page = await browser.newPage({ timezoneId: 'America/Los_Angeles', viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(5000);
  await page.addInitScript(() => localStorage.setItem('sm.splash.seen', 'true'));
  const project = server.app.projects.create({ name: '日历项目' });
  const dueAt = '2030-04-01T01:05:12.345Z';
  const reminderAt = '2030-03-30T01:00:00Z';
  const todo = server.app.createTodo({ title: '本地三月末', projectId: project.id, dueAt, reminderAt });
  server.app.createTodo({ title: '尚未安排', projectId: project.id, waitingOn: '资料复核员回复' });
  server.app.createTodo({ title: '其他范围', dueAt });
  const done = server.app.createTodo({ title: '完成的待办', projectId: project.id, dueAt });
  server.app.store.put('todos', done.id, { ...done, completedAt: dueAt });
  const read = () => server.app.store.get<Todo>('todos', todo.id)!;
  const root = page.getByRole('region', { name: '待办日历' });
  const base = `${server.url}/#projects/${project.id}/todos`;
  await page.goto(base);
  await page.getByRole('button', { name: '日历', exact: true }).click();
  await expect(root).toBeVisible();
  await page.goto(base + '/month/2030-03-31');
  const entry = root.getByRole('button', { name: /本地三月末/ });
  await expect(root.locator('[data-day="2030-03-31"]')).toContainText(todo.title);
  await expect(root.getByText('其他范围', { exact: false })).toHaveCount(0);
  await expect(root.getByText('完成的待办', { exact: false })).toHaveCount(0);
  await root.getByRole('checkbox', { name: '显示已完成' }).check();
  await expect(root.getByText('完成的待办', { exact: false })).toBeVisible();
  await page.route(`**/todos/${todo.id}`, route => route.fulfill({
    status: 503, contentType: 'application/json', body: JSON.stringify({ error: '暂时无法保存' }),
  }), { times: 1 });
  const target = root.locator('[data-day="2030-03-27"]');
  await entry.dragTo(target);
  await expect(page.getByText('没有改期成功：暂时无法保存', { exact: true })).toBeVisible();
  assert.equal(read().dueAt, dueAt);
  await entry.dragTo(target);
  await expect.poll(() => read().dueAt).toBe('2030-03-28T01:05:12.345Z');
  assert.equal(read().reminderAt, reminderAt);
  await root.getByRole('button', { name: '周', exact: true }).click();
  await root.getByRole('button', { name: '查看 2030-03-27', exact: true }).click();
  await expect(page).toHaveURL(/\/day\/2030-03-27$/);
  await page.reload();
  await entry.click();
  const editor = page.getByRole('dialog', { name: '编辑待办' });
  await expect(editor.getByLabel('截止时间', { exact: true })).toHaveValue('18:05');
  await editor.getByLabel('负责人', { exact: true }).fill('预算协调员');
  await editor.getByLabel('优先级', { exact: true }).selectOption('low');
  await editor.getByLabel('截止时间', { exact: true }).fill('08:40');
  await editor.getByRole('button', { name: '保存' }).click();
  await expect.poll(() => read().dueAt).toBe('2030-03-27T15:40:00.000Z');
  await expect(editor).toHaveCount(0);
  assert.equal(read().priority, 'low');
  assert.equal(read().responsiblePerson, '预算协调员');
  await expect(entry).toHaveAccessibleName(/08:40/);
  const dropSlot = root.locator('[data-day="2030-03-27"][data-hour="10"]');
  await entry.dragTo(dropSlot);
  await expect.poll(() => read().dueAt).toBe('2030-03-27T17:30:00.000Z');
  await page.reload();
  await expect(dropSlot.getByRole('button', { name: /10:30.*本地三月末/ })).toBeVisible();
  assert.equal(read().reminderAt, reminderAt);
  // Another client wins after this page has already started dragging.
  const newer = '2030-03-27T18:15:00.000Z';
  await page.route(`**/todos/${todo.id}`, async route => {
    assert.equal(route.request().postDataJSON().expectedDueAt, read().dueAt);
    server.app.updateTodo(todo.id, { dueAt: newer });
    await route.continue();
  }, { times: 1 });
  const dragData = await page.evaluateHandle(() => new DataTransfer());
  await entry.dispatchEvent('dragstart', { dataTransfer: dragData });
  await root.locator('[data-day="2030-03-27"][data-hour="12"]').dispatchEvent('drop', { dataTransfer: dragData });
  await dragData.dispose();
  await expect(page.getByText(/没有改期成功：截止时间已被修改/)).toBeVisible();
  await expect(entry).toHaveAccessibleName(/11:15/);
  assert.equal(read().dueAt, newer);
  // An open editor must neither replace a concurrent due date nor revert unrelated notes.
  await entry.click();
  server.app.updateTodo(todo.id, { dueAt: '2030-03-27T19:00:00.000Z', notes: '合成的新备注' });
  await editor.getByLabel('截止时间', { exact: true }).fill('13:00');
  await editor.getByRole('button', { name: '保存' }).click();
  await expect(editor).toBeVisible();
  await expect(page.getByText('截止时间已被修改，请核对最新时间后重新改期', { exact: true })).toBeVisible();
  assert.equal(read().dueAt, '2030-03-27T19:00:00.000Z');
  await editor.getByRole('button', { name: '取消' }).click();
  await expect(entry).toHaveAccessibleName(/12:00/);
  await entry.click();
  server.app.updateTodo(todo.id, { notes: '同时保存的备注' });
  await editor.getByLabel('截止时间', { exact: true }).fill('13:00');
  await editor.getByRole('button', { name: '保存' }).click();
  await expect.poll(() => read().dueAt).toBe('2030-03-27T20:00:00.000Z');
  assert.equal(read().notes, '同时保存的备注');
  await root.getByRole('button', { name: '添加待办 2030-03-27 11:00' }).click();
  const panel = page.locator('#panel-todos');
  await panel.getByLabel('新待办优先级').selectOption('high');
  await panel.getByRole('textbox', { name: '添加待办' }).fill('日历时段新建');
  await panel.getByRole('button', { name: '添加', exact: true }).click();
  await expect(root.getByRole('button', { name: /日历时段新建/ })).toBeVisible();
  const created = server.app.store.list<Todo>('todos').find(item => item.title === '日历时段新建')!;
  assert.equal(created.projectId, project.id);
  assert.equal(created.priority, 'high');
  assert.equal(created.dueAt, '2030-03-27T18:00:00.000Z');
  await root.getByRole('button', { name: '下一页' }).click();
  await expect(page).toHaveURL(/\/day\/2030-03-28$/);
  await root.getByRole('button', { name: '1 项没有截止日期，查看列表' }).click();
  await expect(panel.locator('.todo', { hasText: '尚未安排' })).toBeVisible();
  const springDue = '2030-03-10T09:30:00.000Z'; // 01:30 before the local clock jumps to 03:00.
  const spring = server.app.createTodo({ title: '切换夏令时的待办', projectId: project.id, dueAt: springDue });
  await page.goto(base + '/week/2030-03-10');
  const skippedHour = root.locator('[data-day="2030-03-10"][data-hour="2"]');
  const springEntry = root.getByRole('button', { name: /切换夏令时的待办/ });
  await springEntry.dragTo(skippedHour);
  await expect(page.getByText(/没有改期成功：截止时间无效/)).toBeVisible();
  assert.equal(server.app.store.get<Todo>('todos', spring.id)?.dueAt, springDue);
  const previousDay = root.locator('[data-day="2030-03-09"][data-hour="2"]');
  await springEntry.dragTo(previousDay);
  await expect.poll(() => server.app.store.get<Todo>('todos', spring.id)?.dueAt).toBe('2030-03-09T10:30:00.000Z');
  const disabled = await fetch(server.url + '/api/v1/plugins/todo-calendar', {
    method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ enabled: false }),
  });
  assert.equal(disabled.status, 200);
  await page.goto(base + '/month/2030-03-31');
  await page.reload();
  await expect(panel.getByRole('group', { name: '待办视图' })).toBeHidden();
  await expect(root).toHaveCount(0);
  await expect(page).toHaveURL(base);
  await expect(panel.locator('.todo', { hasText: '尚未安排' })).toBeVisible();
  // The list uses the browser's civil week even when the calendar plugin is disabled.
  await page.clock.setFixedTime(new Date('2030-03-27T12:00:00-07:00'));
  const nextWeek = server.app.createTodo({ projectId: project.id, title: '下周边界', dueAt: '2030-04-01T07:00:00Z' });
  server.app.createTodo({ projectId: project.id, title: '本周最后一刻', dueAt: '2030-04-01T06:59:59Z', priority: 'low' });
  server.app.store.put('supervision.signals', 'needs-owner', { id: 'needs-owner', kind: 'needs_you', todoId: nextWeek.id });
  await page.reload();
  const period = panel.getByLabel('按截止日期筛选');
  const sort = panel.getByLabel('分组内排序');
  await period.selectOption('none');
  await expect(panel.locator('.todo')).toHaveCount(1);
  await expect(panel.locator('.todo')).toContainText('尚未安排');
  await period.selectOption('week');
  await expect(panel.locator('.todo', { hasText: '切换夏令时的待办' })).toBeVisible();
  await expect(panel.locator('.todo', { hasText: '尚未安排' })).toHaveCount(0);
  await expect(panel.locator('.todo', { hasText: '其他范围' })).toHaveCount(0);
  await sort.selectOption('priority');
  await page.reload();
  await expect(panel.locator('.todo', { hasText: '下周边界' })).toHaveCount(0);
  await expect(panel.locator('.todo', { hasText: '本周最后一刻' })).toBeVisible();
  await expect(panel.getByRole('button', { name: '另有 1 项需要你处理，查看全部期限' })).toBeVisible();
  await expect(sort).toHaveValue('priority');
  await expect(period).toHaveValue('week');
  const sameSection = panel.locator('[data-section]').filter({ has: page.locator('.todo', { hasText: created.title }) });
  await expect(sameSection.locator('.todo').first()).toContainText(created.title);
  await panel.getByRole('searchbox').fill('尚未安排');
  await expect(panel.getByText('没有匹配的待办')).toBeVisible();
  await period.selectOption('all');
  await expect(panel.locator('.todo')).toHaveCount(1);
  await expect(panel.locator('.todo')).toContainText('尚未安排');
  await panel.getByRole('searchbox').fill('资料复核员');
  await expect(panel.locator('.todo')).toHaveCount(1);
  await expect(panel.locator('.todo')).toContainText('尚未安排');
  await panel.getByRole('searchbox').fill('预算协调员');
  await expect(panel.locator('.todo')).toHaveCount(1);
  await expect(panel.locator('.todo')).toContainText('负责人 预算协调员');
  await panel.locator('.todo').getByRole('button', { name: /本地三月末/ }).click();
  await editor.getByLabel('负责人', { exact: true }).fill('');
  await editor.getByRole('button', { name: '保存' }).click();
  await expect.poll(() => read().responsiblePerson).toBeUndefined();
  await expect(panel.locator('.todo')).toHaveCount(0);
});
