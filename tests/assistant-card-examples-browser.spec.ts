import assert from 'node:assert/strict';
import {mkdir,mkdtemp,rm,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import test from 'node:test';
import {chromium,expect} from '@playwright/test';
import {startServer} from '../apps/server/src/index.ts';

test('高级界面的助理卡片示例支持六类本地预览，操作不写入工作台', {timeout:30000},async t=>{
  const dataDir=await mkdtemp(join(tmpdir(),'card-examples-'));
  const extension = join(dataDir,'extensions','review');
  await mkdir(extension,{recursive:true});
  await writeFile(join(extension,'super-mario.extension.json'),JSON.stringify({id:'review.local',version:'1.0.0',apiVersion:1,main:'index.mjs',navigation:[{id:'notes',label:'打开评审备注',route:'#agent/extensions/review.local/notes'}]}));
  await writeFile(join(extension,'index.mjs'),`export default {id:'review.local',name:'合成评审',capabilities:[],activate(ctx){
    ctx.contribute('web_extensions','patch',{slot:'advanced-interface',renderer:'diff',title:'变更摘录',patch:'-before\\n+<img src=x>\\n',fallback:'新增一行'});
    ctx.contribute('web_extensions','chart',{slot:'advanced-interface',renderer:'chart',kind:'bar',title:'数量变化',unit:'件',points:[{label:'昨日',value:-3},{label:'今日',value:5,display:'新增 5 件'}],fallback:'数量变化摘要'});
    for (const kind of ['line','area','bar']) ctx.contribute('web_extensions','compare-'+kind,{slot:'advanced-interface',renderer:'chart',kind,title:'收支 '+kind,series:[
      {name:'收入',points:[{label:'周一',value:2},{label:'周二',value:5}]},
      {name:'支出',points:[{label:'周一',value:-3},{label:'周二',value:-1}]}
    ],fallback:'收支摘要'});
    ctx.contribute('web_extensions','allocation',{slot:'advanced-interface',renderer:'chart',kind:'bar',stacked:true,title:'单日分配',series:[
      {name:'甲',points:[{label:'今日',value:Number.MAX_VALUE}]},
      {name:'乙',points:[{label:'今日',value:Number.MAX_VALUE}]}
    ],fallback:'分配摘要'});
    ctx.contribute('web_extensions','line',{slot:'advanced-interface',renderer:'chart',kind:'line',title:'单点趋势',points:[{label:'当前',value:0}],fallback:'当前为零'});
    ctx.contribute('web_extensions','area',{slot:'advanced-interface',renderer:'chart',kind:'area',title:'跨零走势',points:[{label:'昨日',value:-1},{label:'今日',value:1}],fallback:'由负转正'});
    for (const kind of ['pie','donut']) ctx.contribute('web_extensions',kind,{slot:'advanced-interface',renderer:'chart',kind,title:'占比 '+kind,
      points:[{label:'甲',value:Number.MAX_VALUE},{label:'乙',value:Number.MAX_VALUE},{label:'扣减',value:-2}],fallback:'两类各占一半'});
    ctx.contribute('web_extensions','candles',{slot:'advanced-interface',renderer:'chart',kind:'candlestick',title:'价格记录',
      points:[{label:'首日',value:12,open:10,high:15,low:9,volume:24},{label:'次日',value:11,open:12,high:13,low:10}],fallback:'价格摘要'});
    const stream={slot:'advanced-interface',renderer:'stream',title:'处理记录',lines:['已开始'],fallback:'等待记录'};
    ctx.contribute('web_extensions','stream',stream);
    ctx.onEvent(event=>{if(event.type==='review.progress')stream.lines.push(event.data.text);});
    ctx.contribute('web_extensions','review.local/notes',{slot:'advanced-interface',renderer:'form',title:'评审备注',fields:[{name:'note',label:'备注',required:true,multiline:true,initial:'待复核'},{name:'priority',label:'等级',options:['普通','优先'],initial:'普通'}],fallback:'备注表单'});
    ctx.provide('review.local.submit_form',async input=>({message:input.values.priority+'：'+input.values.note}));
    ctx.contribute('web_extensions','future',{slot:'advanced-interface',renderer:'future',title:'其他格式',fallback:'纯文字说明'});
  }}`);
  const draftExtension = join(dataDir,'extensions','draft');
  await mkdir(draftExtension,{recursive:true});
  await writeFile(join(draftExtension,'super-mario.extension.json'),JSON.stringify({id:'draft',version:'1.0.0',apiVersion:1,main:'index.mjs'}));
  await writeFile(join(draftExtension,'index.mjs'),`export default {id:'draft',name:'草稿插件',capabilities:[],activate(ctx){
    ctx.contribute('web_extensions','draft/notes',{slot:'advanced-interface',renderer:'form',title:'草稿备注',fields:[{name:'note',label:'草稿'}],fallback:'草稿表单'});
  }}`);
  const server=await startServer({host:'127.0.0.1',port:0,dataDir,demo:true});
  t.after(async()=>{await server.close();await rm(dataDir,{recursive:true,force:true});});
  const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE});
  t.after(()=>browser.close());
  const page=await browser.newPage();
  await page.addInitScript(()=>localStorage.setItem('sm.splash.seen','true'));
  let disconnectEvents: (() => Promise<void>) | undefined;
  let connections = 0;
  await page.routeWebSocket('**/api/v1/events*', ws => {
    const upstream = ws.connectToServer();
    connections++;
    disconnectEvents = async () => { await ws.close(); await upstream.close(); };
  });
  await page.goto(server.url+'/#agent');
  await page.getByRole('button',{name:'插件配置',exact:true}).click();
  const settings=page.getByRole('dialog',{name:'插件配置'});
  await settings.getByLabel('搜索插件').fill('review.local');
  await settings.getByRole('button',{name:'打开评审备注'}).click();
  await expect(page).toHaveURL(server.url+'/#agent/extensions/review.local/notes');
  await expect(page.getByRole('region',{name:'评审备注'})).toBeVisible();
  const entry=page.getByRole('button',{name:'助理卡片示例',exact:true});
  await expect(entry).toBeVisible();
  const stream=page.getByRole('region',{name:'处理记录'}).locator('pre');
  await expect(stream).toHaveText('已开始');
  await stream.focus();
  await stream.evaluate(pre => {
    const range=document.createRange();
    range.selectNodeContents(pre.firstChild!);
    const selection=window.getSelection()!;
    selection.removeAllRanges();
    selection.addRange(range);
  });
  server.app.events.publish('review.progress',{text:'已处理首批'});
  await expect(stream).toHaveText('已开始\n已处理首批');
  await expect(stream).toBeFocused();
  assert.equal(await page.evaluate(()=>window.getSelection()?.toString()),'已开始');
  await page.reload();
  await expect(page.getByRole('region',{name:'评审备注'})).toBeVisible();
  await expect(stream).toHaveText('已开始\n已处理首批');
  const beforeDisconnect = connections;
  assert.ok(disconnectEvents);
  await disconnectEvents();
  server.app.events.publish('review.progress',{text:'断线期间第二批'});
  server.app.events.publish('review.progress',{text:'断线期间第三批'});
  await expect.poll(()=>connections).toBeGreaterThan(beforeDisconnect);
  await expect(stream).toHaveText('已开始\n已处理首批\n断线期间第二批\n断线期间第三批');
  server.app.events.publish('review.progress',{text:'重连后完成'});
  await expect(stream).toHaveText('已开始\n已处理首批\n断线期间第二批\n断线期间第三批\n重连后完成');
  const patch=page.getByRole('region',{name:'变更摘录'});
  const patchText='-before\n+<img src=x>\n';
  await expect(patch.locator('.diff-line--del')).toHaveText('-before');
  await expect(patch.locator('.diff-line--add')).toHaveText('+<img src=x>');
  await page.context().grantPermissions(['clipboard-read','clipboard-write'],{origin:server.url});
  await patch.getByRole('button',{name:'复制补丁'}).click();
  await expect(patch.getByRole('status')).toHaveText('已复制补丁');
  assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),patchText);
  await expect(patch.locator('img')).toHaveCount(0);
  await expect(page.getByRole('region',{name:'其他格式'})).toContainText('纯文字说明');
  for (const [kind,selector,count] of [['line','polyline',2],['area','polygon',2],['bar','rect',4]] as const) {
    const comparison=page.getByRole('region',{name:'收支 '+kind});
    await expect(comparison.locator('svg '+selector)).toHaveCount(count);
    const cursor=comparison.getByRole('slider');
    await cursor.press('ArrowRight');
    await expect(cursor).toHaveAttribute('aria-valuetext','周二，收入 5，支出 -1');
  }
  const shares=page.getByRole('region',{name:'单日分配'}).locator('svg rect');
  await expect(shares).toHaveCount(2);
  await expect(shares.first()).toHaveAttribute('width','150');
  await expect(shares.last()).toHaveAttribute('x','150');
  const chart=page.getByRole('region',{name:'数量变化'});
  await expect(chart.getByRole('cell')).toHaveText(['-3 件','新增 5 件']);
  await expect(chart.locator('svg rect')).toHaveCount(2);
  await expect(page.getByRole('region',{name:'单点趋势'}).locator('circle')).toHaveAttribute('cx','150');
  const point=chart.getByRole('slider',{name:'查看数据点'});
  await expect(point).toHaveAttribute('aria-valuetext','昨日，数值 -3 件');
  await point.press('ArrowRight');
  await expect(point).toHaveAttribute('aria-valuetext','今日，数值 新增 5 件');
  server.app.events.publish('review.progress',{text:'追加复核记录'});
  await expect(stream).toContainText('追加复核记录');
  await expect(point).toBeFocused();
  await expect(point).toHaveAttribute('aria-valuetext','今日，数值 新增 5 件');
  await chart.getByRole('button',{name:'复制数据点'}).click();
  await expect(chart.getByRole('status')).toHaveText('已复制数据点');
  assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),'数量变化\n今日，数值 新增 5 件');
  const area=page.getByRole('region',{name:'跨零走势'});
  await expect(area.locator('polygon')).toHaveAttribute('points','75,50 75,96 225,4 225,50');
  await expect(area.locator('polyline')).toHaveAttribute('points','75,96 225,4');
  for (const kind of ['pie','donut']) {
    const round=page.getByRole('region',{name:'占比 '+kind});
    await expect(round.getByRole('cell',{name:'50%',exact:true})).toHaveCount(2);
    await expect(round.getByRole('row',{name:/扣减/})).toContainText('0%');
    await expect(round.locator('div[aria-hidden]')).toHaveCSS('background-image',/conic-gradient/);
  }
  const prices=page.getByRole('region',{name:'价格记录'});
  await expect(prices.getByRole('cell')).toHaveText(['10','15','9','12','24','12','13','10','11','—']);
  await expect(prices.locator('svg line')).toHaveCount(2);
  await expect(prices.locator('svg rect')).toHaveCount(3);
  await patch.locator('code').evaluate(code => {
    const range=document.createRange();
    range.selectNodeContents(code);
    const selection=window.getSelection()!;
    selection.removeAllRanges();
    selection.addRange(range);
  });
  const selectionBefore=await page.evaluate(()=>window.getSelection()?.toString());
  assert.ok(selectionBefore?.includes('+<img src=x>'));
  const examplesApi=server.url+'/api/v1/plugins/assistant-card-examples';
  assert.ok((await page.request.post(examplesApi,{data:{enabled:false}})).ok());
  await expect(entry).toBeHidden();
  assert.equal(await page.evaluate(()=>window.getSelection()?.toString()),selectionBefore);
  assert.ok((await page.request.post(examplesApi,{data:{enabled:true}})).ok());
  await expect(entry).toBeVisible();
  const form=page.getByRole('region',{name:'评审备注'});
  await expect(form.getByLabel('备注')).toHaveValue('待复核');
  await expect(form.getByLabel('等级')).toHaveValue('普通');
  await form.getByLabel('等级').selectOption('优先');
  await form.getByLabel('备注').fill('合成评审');
  await form.getByRole('button',{name:'提交'}).click();
  await expect(form.getByRole('status')).toHaveText('优先：合成评审');
  await expect(form.getByRole('button',{name:'提交'})).toBeDisabled();
  await form.getByLabel('备注').fill('另一条合成评审');
  await expect(form.getByRole('button',{name:'提交'})).toBeEnabled();
  await form.getByLabel('备注').fill('合成评审');
  await expect(form.getByRole('button',{name:'提交'})).toBeDisabled();
  const revisedNote='修订评审\n\n补充交接说明';
  await form.getByLabel('备注').fill(revisedNote);
  await form.getByRole('button',{name:'提交'}).click();
  await expect.poll(()=>form.getByRole('status').textContent()).toBe('优先：'+revisedNote);
  const draft=page.getByRole('region',{name:'草稿备注'});
  await draft.getByLabel('草稿',{exact:true}).fill('尚未提交');
  await draft.getByRole('button',{name:'提交'}).click();
  await expect(draft.getByRole('status')).toHaveText('表单所属插件未提供提交服务');
  await expect(draft.getByLabel('草稿',{exact:true})).toBeEditable();
  const endpoint=server.url+'/api/v1/plugin-forms/review.local/notes';
  assert.equal((await page.request.post(endpoint,{data:{note:' '}})).status(),400);
  assert.equal((await page.request.post(endpoint,{data:{note:'评审',priority:'未定义'}})).status(),400);
  let received=0;
  await page.route(endpoint,async route=>{
    const response=await route.fetch();
    assert.equal(response.status(),200);
    received++;
    await route.abort('failed');
  });
  await form.getByLabel('备注').fill('回执中断的评审');
  await form.getByRole('button',{name:'提交'}).click();
  await expect(form.getByRole('status')).toContainText('提交结果待核对');
  await expect(form.getByRole('button',{name:'提交'})).toBeDisabled();
  await form.locator('form').evaluate(el=>(el as HTMLFormElement).requestSubmit());
  assert.equal(received,1);
  const stopped=await page.request.post(server.url+'/api/v1/plugins/review.local',{data:{enabled:false}});
  assert.equal(stopped.status(),200);
  assert.equal((await page.request.post(endpoint,{data:{note:'旧页提交'}})).status(),404);
  await expect(patch).toHaveCount(0);
  await expect(chart).toHaveCount(0);
  await expect(page.getByRole('region',{name:'其他格式'})).toHaveCount(0);
  const writes:string[]=[],errors:string[]=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{
    const path=new URL(request.url()).pathname;
    // The shell sends a presence heartbeat independently of the examples.
    if(path.startsWith('/api/') && path!=='/api/v1/presence' && !['GET','HEAD','OPTIONS'].includes(request.method()))writes.push(request.method()+' '+path);
  });
  await entry.click();
  const dialog=page.getByRole('dialog',{name:'助理卡片示例'});
  const choose=dialog.getByLabel('示例类型');
  await expect(choose.locator('option')).toHaveText(['决策','比较','进度','表单','图表','HTML']);
  await choose.selectOption('decision');
  await dialog.getByRole('button',{name:'B 队列去重'}).click();
  await expect(dialog.getByRole('status')).toContainText(/队列去重|选项 B/);
  await choose.selectOption('compare');
  await dialog.getByRole('button',{name:'详细依据'}).click();
  await expect(dialog.getByRole('status')).not.toBeEmpty();
  await choose.selectOption('progress');
  const version=dialog.getByLabel('进度版本');
  await version.selectOption('before');
  await expect(dialog.getByRole('progressbar')).toHaveAttribute('value','1');
  await version.selectOption('after');
  await expect(dialog.getByRole('progressbar')).toHaveAttribute('value','3');
  await expect(dialog).toContainText('剩余 0 步');
  await choose.selectOption('form');
  await dialog.getByLabel('任务名称').fill('合成验收任务');
  await dialog.getByLabel('优先级').selectOption('high');
  await dialog.getByLabel('完成后通知').uncheck();
  await dialog.getByRole('button',{name:'提交',exact:true}).click();
  await expect(dialog.getByRole('status')).toContainText('合成验收任务');
  await expect(dialog.getByRole('status')).toContainText('完成后通知：否');
  await dialog.getByRole('button',{name:'重置示例',exact:true}).click();
  await expect(dialog.getByLabel('任务名称')).toHaveValue('');
  await expect(dialog.getByLabel('优先级')).toHaveValue('normal');
  await expect(dialog.getByLabel('完成后通知')).toBeChecked();
  await expect(dialog.getByRole('status')).toBeEmpty();
  await choose.selectOption('chart');
  await expect(dialog.getByRole('img',{name:'测试耗时依次为 8、6、5 分钟'})).toBeVisible();
  await expect(dialog.getByText('纯文字回退',{exact:true})).toBeVisible();
  await choose.selectOption('html');
  await expect(dialog.getByText('纯文字回退',{exact:true})).toBeVisible();
  await expect(dialog).toContainText('HTML 示例仅展示文字回退');
  await expect(dialog).toContainText('需要在对话中确认');
  await expect(dialog.locator('iframe,object,embed')).toHaveCount(0);
  await dialog.getByRole('button',{name:'关闭',exact:true}).click();
  await expect(dialog).not.toBeVisible();
  await entry.click();await expect(dialog).toBeVisible();
  assert.deepEqual(writes,[]);assert.deepEqual(errors,[]);
  const disabled=await page.request.post(server.url+'/api/v1/plugins/assistant-card-examples',{data:{enabled:false}});
  assert.equal(disabled.status(),200);
  await expect(dialog).not.toBeVisible();await expect(entry).not.toBeVisible();
});
